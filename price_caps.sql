-- =============================================================================
-- price_caps — довідник цінових стель НКРЕКП (РДН/ВДР та БР) у часі.
--
-- Призначення: де-biasing аналізу трендів і виявлення годин «біля стелі».
-- Стелі РДН і ВДР у всіх постановах однакові → market='RDN' покриває й ВДР.
-- hour_from включно, hour_to виключно (24 = кінець доби). cap_* у грн/МВт·год.
--
-- Застосувати:  docker exec -i oree_pg psql -U oree -d oree < price_caps.sql
--
-- Пошук стелі для (дата, година, ринок):
--   SELECT cap_max FROM price_caps
--   WHERE market='RDN' AND :d BETWEEN valid_from AND COALESCE(valid_to,'9999-12-31')
--     AND :h >= hour_from AND :h < hour_to;
-- =============================================================================

CREATE TABLE IF NOT EXISTS price_caps (
    valid_from DATE        NOT NULL,
    valid_to   DATE,                       -- NULL = чинна досі
    market     VARCHAR(8)  NOT NULL,       -- 'RDN' (=ВДР) або 'BR'
    hour_from  SMALLINT    NOT NULL,       -- 0..23, включно
    hour_to    SMALLINT    NOT NULL,       -- виключно (24 = кінець доби)
    cap_max    NUMERIC(12,2),
    cap_min    NUMERIC(12,2),
    postanova  TEXT,
    PRIMARY KEY (valid_from, market, hour_from)
);

